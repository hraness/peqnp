const signName = sign => sign > 0 ? "pos" : "neg";
// The Rust generator's u64 seed fields occupy disjoint bits; the report
// emits the effective seed as a decimal string because it exceeds 2^53.
const effectiveSeed = (base, n, t, b) => (BigInt(base) ^ (BigInt(n) << 32n) ^ (BigInt(t) << 40n) ^ (BigInt(b) << 48n)).toString();

// The ladder control exactly as the protocol constructs it: y_1..y_k are
// 1..k, x_1..x_j are k+1..k+j; F_k on x_1 with the y chain, then the x
// chain. The negative variant negates every occurrence of every x.
function ladder(k, j, sign) {
  const y = i => i;
  const x = i => (k + i) * sign;
  const clauses = [[x(1), y(1)]];
  for (let i = 1; i < k; i++) clauses.push([-y(i), y(i + 1)]);
  clauses.push([-y(k), x(1)]);
  for (let i = 1; i < j; i++) clauses.push([-x(i), x(i + 1)]);
  return clauses;
}
const ladderUnits = (k, j, sign) => Array.from({ length: j }, (_, i) => (k + i + 1) * sign);

// The fixed 338-case corpus: 176 primary cases in protocol enumeration
// order, then the 162 fragment-interface-v1 cases regenerated by that
// validator's builder. Engineered inputs (ladders, v1 chains and parity
// cycles) are regenerated exactly; the pseudorandom clauses are identified
// by their parameters and effective seed and checked for count, width, and
// distinct variables only.
function expectedCases() {
  const cases = new Map();
  const add = (id, family, secondary, variables, metadata, prefix, ternary, binary) =>
    cases.set(id, { metadata: { family, secondary, variables, ...EMPTY_METADATA, ...metadata }, prefix, ternary, binary });
  for (const seed of SEEDS) for (const n of VARIABLES) for (const t of DENSITIES) {
    for (const [label, b] of [["b=n", n], ["b=2n", 2 * n], ["b=3n", 3 * n], ["b=4n", 4 * n]]) {
      add(`random-n${n}-t${t}-b${b}-s${seed}`, "random-mixed", false, n,
        { seed, effective_seed: effectiveSeed(seed, n, t, b), density: t, binary_count: b, binary_label: label }, [], t * n, b);
    }
  }
  for (const seed of SEEDS) for (const n of VARIABLES) for (const [label, b] of [["b=n", n], ["b=2n", 2 * n]]) {
    add(`fragment-only-n${n}-b${b}-s${seed}`, "fragment-only", false, n,
      { seed, effective_seed: effectiveSeed(seed, n, 0, b), density: 0, binary_count: b, binary_label: label }, [], 0, b);
  }
  for (const [k, j] of LADDERS) for (const sign of [1, -1]) {
    add(`ladder-k${k}-j${j}-${signName(sign)}`, "ladder-control", false, k + j,
      { density: 0, binary_count: k + j, ladder_k: k, ladder_j: j, chain_length: k, sign }, ladder(k, j, sign), 0, 0);
  }
  require(cases.size === PRIMARY_CASES, "Primary corpus enumeration must yield exactly 176 cases.");
  for (const [id, fixed] of fragmentCases()) {
    const { family, variables, ...metadata } = fixed.metadata;
    add("v1:" + id, "v1:" + family, true, variables, metadata, fixed.prefix, fixed.ternary, fixed.binary);
  }
  require(cases.size === PRIMARY_CASES + SECONDARY_CASES, "Corpus enumeration must yield exactly 338 cases.");
  return cases;
}

function boundedCnf(value, variables, clauses) {
  return Array.isArray(value) && value.length === clauses && value.every(clause => Array.isArray(clause) &&
    clause.length <= MAX_WIDTH && clause.every(lit => literal(lit, variables)));
}
const drawn = (clause, width) => clause.length === width && new Set(clause.map(Math.abs)).size === width;
const idle = arm => ["extraction", "append", "residual"].every(phase => arm.phases[phase].work_units === 0);
const completed = arm => arm.outcome !== "unknown-budget";
const extracted = arm => completed(arm) && arm.certificate.kind === "sat";

// One fragment arm (per-literal or settled): the fragment-interface-v1 arm
// invariants, with every certificate and clue path re-checked against the
// raw clauses of this case.
function validateFragmentArm(arm, row, name) {
  keys(arm, ARM_FIELDS, name + " arm");
  keys(arm.phases, PHASES, name + " phases");
  for (const phase of PHASES) work(arm.phases[phase]);
  require(arm.fragment_work_units === sum(FRAGMENT_PHASES.map(phase => arm.phases[phase].work_units)) &&
    arm.residual_work_units === arm.phases.residual.work_units && arm.search_nodes === arm.phases.residual.search_nodes &&
    arm.total_work_units === sum([arm.fragment_work_units, arm.residual_work_units]) && arm.total_work_units <= BUDGET, name + " phase totals are inconsistent or exceed the shared budget.");
  require(OUTCOMES.includes(arm.outcome), "Invalid " + name + " outcome.");
  require(Array.isArray(arm.clues) && distinctLiterals(arm.derived_units, row.variables), "Clues must be a list and derived units distinct declared literals.");
  const reference = row.reference;
  if (!completed(arm)) {
    require(arm.total_work_units === BUDGET, "Unknown-budget requires exhausted work budget.");
    require(arm.certificate === null && arm.clues.length === 0 && arm.derived_units.length === 0, "Unknown " + name + " arm cannot carry a certificate, clues, or units.");
    return;
  }
  require((arm.outcome === "sat") === reference.sat, name + " decision disagrees with the supplied reference label.");
  validateCertificate(arm.certificate, row.input, row.variables);
  if (arm.certificate.kind !== "sat") {
    require(arm.outcome === "unsat" && arm.clues.length === 0 && arm.derived_units.length === 0 && idle(arm), name + " UNSAT certificate must decide the case without extraction, appends, or residual work.");
    return;
  }
  require(arm.phases.residual.work_units > 0, name + " SAT certificate must be followed by the residual decision.");
  for (const clue of arm.clues) {
    keys(clue, ["literal", "path"], "clue");
    validatePath(clue.path, row.input, -clue.literal, clue.literal, row.variables);
  }
  equal(arm.derived_units, arm.clues.map(clue => clue.literal), name + " derived units differ from the clue literals in order.");
  if (reference.sat) require(arm.derived_units.every(unit => reference.backbone.includes(unit)), name + " derived units must be a subset of the reference backbone.");
  // Family expectations shared by both fragment arms.
  if (row.family === "ladder-control") {
    equal(arm.derived_units, ladderUnits(row.ladder_k, row.ladder_j, row.sign), name + " ladder control must derive exactly the j ladder literals.");
    require(arm.derived_units.every(unit => Math.abs(unit) > row.ladder_k), "Ladder control derived a y literal.");
  }
  if (row.family === "v1:chain-embedded") equal(arm.derived_units, [row.sign], name + " chain-embedded control must derive exactly the selected sign of x.");
  if (row.family === "v1:random-ternary-only") {
    require(arm.derived_units.length === 0, "An empty fragment cannot derive units.");
    require(completed(row.baseline), "Completed residual on an empty fragment implies a completed baseline.");
    equal(arm.phases.residual, row.baseline.work, name + " residual counters on an empty fragment differ from the baseline's work.");
  }
}

function validateChecks(checks, arm, name) {
  keys(checks, CHECK_FIELDS, name + " checks");
  work(checks.work);
  require(checks.certificate_valid === (arm.certificate === null ? null : true) &&
    checks.clues_checked === arm.clues.length && checks.clues_valid === arm.clues.length, name + " checker outcome disagrees with the reported certificate and clues.");
}

function validateObservation(row, fixed) {
  keys(row, OBSERVATION_FIELDS, "observation");
  equal({ family: row.family, secondary: row.secondary, variables: row.variables, seed: row.seed, effective_seed: row.effective_seed, density: row.density, binary_count: row.binary_count,
    binary_label: row.binary_label, ladder_k: row.ladder_k, ladder_j: row.ladder_j, chain_length: row.chain_length, sign: row.sign, cycle_length: row.cycle_length },
  fixed.metadata, "Case metadata differs from the fixed corpus.");
  const clauses = fixed.prefix.length + fixed.ternary + fixed.binary;
  require(boundedCnf(row.input, row.variables, clauses), "Invalid bounded width-at-most-three CNF.");
  equal(row.input.slice(0, fixed.prefix.length), fixed.prefix, "Engineered control input differs from the protocol construction.");
  const random = row.input.slice(fixed.prefix.length);
  require(random.every((clause, index) => drawn(clause, index < fixed.ternary ? 3 : 2)), "Random clause shape differs from its parameters.");
  require(row.clauses === row.input.length && row.fragment_clauses === row.input.filter(clause => clause.length <= 2).length &&
    row.used_variables === new Set(row.input.flat().map(Math.abs)).size, "Clause or used-variable counts differ from the CNF.");
  const reference = row.reference;
  keys(reference, ["model_count", "sat", "backbone", "work"], "reference");
  count(reference.model_count);
  require(reference.model_count <= 2 ** row.variables && reference.sat === (reference.model_count > 0), "Reference model count or label is inconsistent.");
  work(reference.work);
  require(reference.work.assignments === 2 ** row.variables && reference.work.formula_checks >= 2 ** row.variables, "Incomplete reference coverage counters.");
  if (reference.sat) {
    require(distinctLiterals(reference.backbone, row.variables) && new Set(reference.backbone.map(Math.abs)).size === reference.backbone.length, "Reference backbone must list distinct forced literals.");
  } else require(reference.backbone === null, "UNSAT reference cannot define a backbone.");
  const baseline = row.baseline;
  keys(baseline, ["outcome", "work", "total_work_units", "search_nodes"], "baseline arm");
  work(baseline.work);
  require(baseline.total_work_units === baseline.work.work_units && baseline.search_nodes === baseline.work.search_nodes && baseline.total_work_units <= BUDGET, "Baseline totals are inconsistent or exceed the shared budget.");
  require(OUTCOMES.includes(baseline.outcome), "Invalid baseline outcome.");
  if (!completed(baseline)) require(baseline.total_work_units === BUDGET, "Unknown-budget requires exhausted work budget.");
  else require((baseline.outcome === "sat") === reference.sat, "Baseline decision disagrees with the supplied reference label.");
  const { per_literal: perLiteral, settled } = row;
  validateFragmentArm(perLiteral, row, "per_literal");
  validateFragmentArm(settled, row, "settled");
  if (row.family === "v1:contradictory-fragment") {
    require(!reference.sat, "Contradictory-fragment control labeled satisfiable.");
    for (const arm of [perLiteral, settled]) {
      require(arm.outcome === "unsat" && UNSAT_CERTIFICATES.includes(arm.certificate.kind) && idle(arm), "Contradictory-fragment control must be decided UNSAT by the fragment alone.");
    }
  }
  // Settled statistics exist exactly when the settled extraction ran to
  // completion; each vertex is settled by at most one route, and every
  // search appends its root plus one visited entry per search-node event.
  if (extracted(settled)) {
    keys(row.settled_stats, STATS_FIELDS, "settled stats");
    for (const field of STATS_FIELDS) count(row.settled_stats[field]);
    const vertices = 2 * row.variables;
    require(sum([row.settled_stats.searches, row.settled_stats.inherited]) <= vertices && row.settled_stats.settled_good <= vertices, "Settled stats exceed the vertex count.");
    require(row.settled_stats.vertices_visited === sum([row.settled_stats.searches, settled.phases.extraction.search_nodes]), "Settled visited count differs from searches plus search nodes.");
  } else require(row.settled_stats === null, "Settled stats require a completed settled extraction.");
  // Arms 2 and 3 differ in extraction alone: when both completed, the same
  // outcome, fragment certificate, ordered derived units, and identical
  // counters in every phase other than extraction.
  if (completed(perLiteral) && completed(settled)) {
    require(perLiteral.outcome === settled.outcome, "Per-literal and settled arms disagree on the outcome.");
    equal(perLiteral.certificate, settled.certificate, "Per-literal and settled arms disagree on the fragment certificate.");
    equal(perLiteral.derived_units, settled.derived_units, "Per-literal and settled arms derived different units.");
    for (const phase of SHARED_PHASES) equal(perLiteral.phases[phase], settled.phases[phase], "Per-literal and settled arms differ outside the extraction phase.");
  }
  keys(row.checks, ["per_literal", "settled"], "checks");
  validateChecks(row.checks.per_literal, perLiteral, "per_literal");
  validateChecks(row.checks.settled, settled, "settled");
}

function summarize(rows) {
  const tally = (fields, entries) => {
    const result = Object.fromEntries(fields.map(key => [key, 0]));
    for (const [key, value] of entries) result[key] = sum([result[key], value]);
    return result;
  };
  const outcome = arm => arm.outcome === "sat" ? "sat" : arm.outcome === "unsat" ? "unsat" : "unknown";
  const baseline = tally(BASELINE_SUMMARY_FIELDS, rows.flatMap(row => [["work_units", row.baseline.total_work_units], ["search_nodes", row.baseline.search_nodes],
    [outcome(row.baseline), 1], ["complete", Number(completed(row.baseline))]]));
  const fragment = select => ({
    phases: tally(PHASE_SUMMARY_FIELDS, rows.flatMap(row => FRAGMENT_PHASES.map(phase => [phase + "_work_units", select(row).phases[phase].work_units]))),
    ...tally(FRAGMENT_SUMMARY_FIELDS.slice(1), rows.flatMap(row => {
      const arm = select(row);
      return [
        ["fragment_work_units", arm.fragment_work_units], ["residual_work_units", arm.residual_work_units],
        ["total_work_units", arm.total_work_units], ["search_nodes", arm.search_nodes],
        ["derived_units", arm.derived_units.length],
        ["fragment_unsat", Number(arm.certificate !== null && UNSAT_CERTIFICATES.includes(arm.certificate.kind))],
        ["complete", Number(completed(arm))], [outcome(arm), 1],
      ];
    })),
  });
  const perLiteral = fragment(row => row.per_literal);
  const settled = fragment(row => row.settled);
  const withStats = rows.filter(row => row.settled_stats !== null);
  const settledStats = tally(STATS_FIELDS, withStats.flatMap(row => STATS_FIELDS.map(field => [field, row.settled_stats[field]])));
  const perLiteralSearches = sum(rows.map(row => row.per_literal.phases.extraction.rule_attempts));
  const complete = arm => completed(arm) ? arm.total_work_units : null;
  // The extraction phase alone, compared only where both arms completed
  // and the settled extraction ran (a SAT fragment certificate).
  const compared = rows.filter(row => completed(row.per_literal) && extracted(row.settled));
  const extraction = {
    ...tally(EXTRACTION_COMPARISON_FIELDS, [
      ...compared.map(row => [row.settled.phases.extraction.work_units < row.per_literal.phases.extraction.work_units ? "settled_better"
        : row.settled.phases.extraction.work_units > row.per_literal.phases.extraction.work_units ? "settled_worse" : "tied", 1]),
      ["compared", compared.length], ["not_compared", rows.length - compared.length],
      ...compared.flatMap(row => [
        ["per_literal_work_units", row.per_literal.phases.extraction.work_units], ["settled_work_units", row.settled.phases.extraction.work_units],
        ["per_literal_searches", row.per_literal.phases.extraction.rule_attempts], ["settled_searches", row.settled_stats.searches],
      ]),
    ]),
  };
  const referenceWorkUnits = sum(rows.map(row => row.reference.work.work_units));
  return {
    cases: rows.length,
    reference_sat: rows.filter(row => row.reference.sat).length,
    reference_unsat: rows.filter(row => !row.reference.sat).length,
    reference_work_units: referenceWorkUnits,
    checker_work_units: sum(rows.flatMap(row => [row.checks.per_literal.work.work_units, row.checks.settled.work.work_units])),
    certificates_checked: sum(rows.flatMap(row => [row.checks.per_literal, row.checks.settled].map(checks => Number(checks.certificate_valid !== null)))),
    clues_checked: sum(rows.flatMap(row => [row.checks.per_literal.clues_checked, row.checks.settled.clues_checked])),
    arms: { baseline, per_literal: perLiteral, settled },
    searches: { per_literal: perLiteralSearches, settled: settledStats.searches },
    settled_stats: settledStats,
    settled_stats_cases: withStats.length,
    comparisons: {
      settled_vs_baseline: comparison(rows.map(row => [complete(row.settled), complete(row.baseline)])),
      settled_vs_per_literal: comparison(rows.map(row => [complete(row.settled), complete(row.per_literal)])),
      per_literal_vs_baseline: comparison(rows.map(row => [complete(row.per_literal), complete(row.baseline)])),
      extraction_settled_vs_per_literal: extraction,
    },
    enumeration_ratio: {
      reference_over_baseline: ratio(referenceWorkUnits, baseline.work_units),
      reference_over_per_literal: ratio(referenceWorkUnits, perLiteral.total_work_units),
      reference_over_settled: ratio(referenceWorkUnits, settled.total_work_units),
    },
  };
}

function validateSummaryShape(summary) {
  keys(summary, SUMMARY_FIELDS, "summary");
  keys(summary.arms, ["baseline", "per_literal", "settled"], "summary arms");
  keys(summary.arms.baseline, BASELINE_SUMMARY_FIELDS, "baseline summary");
  for (const arm of ["per_literal", "settled"]) {
    keys(summary.arms[arm], FRAGMENT_SUMMARY_FIELDS, arm + " summary");
    keys(summary.arms[arm].phases, PHASE_SUMMARY_FIELDS, arm + " phase summary");
  }
  keys(summary.searches, ["per_literal", "settled"], "search summary");
  keys(summary.settled_stats, STATS_FIELDS, "settled stats summary");
  keys(summary.comparisons, COMPARISONS, "summary comparisons");
  for (const name of TOTAL_COMPARISONS) keys(summary.comparisons[name], COMPARISON_FIELDS, "comparison");
  keys(summary.comparisons.extraction_settled_vs_per_literal, EXTRACTION_COMPARISON_FIELDS, "extraction comparison");
  keys(summary.enumeration_ratio, RATIO_FIELDS, "enumeration ratio");
}

function validateGroups(groups, rows, label, name) {
  const labels = [...new Set(rows.map(label))].sort();
  keys(groups, labels, name);
  for (const value of labels) {
    validateSummaryShape(groups[value]);
    equal(groups[value], summarize(rows.filter(row => label(row) === value)), name.replace(/ summaries$/, "") + " summary differs from observations.");
  }
  return labels;
}

function validateSection(section, rows, { name, fields, mixedFamily, subtotalKey, families }) {
  keys(section, fields, name + " section");
  validateSummaryShape(section.summary);
  require(section.summary.cases === rows.length, name + " section case count differs from its observations.");
  equal(section.summary, summarize(rows), name + " summary differs from per-case observations.");
  const actual = validateGroups(section.families, rows, row => row.family, name + " family summaries");
  equal(Object.fromEntries(actual.map(family => [family, section.families[family].cases])), families, name + " family sizes differ from the fixed corpus.");
  validateGroups(section[subtotalKey], rows.filter(row => row.family === mixedFamily), row => row.binary_label, name + " binary-count summaries");
}

export function validateExtractionCost(report) {
  keys(report, ["schema_version", "experiment", "status", "proof_status", "protocol_sha256", "arm_budget", "counter_model", "limitations", "corpus", "observations", "outside_arms", "arms", "comparison", "encoding", "primary", "secondary"], "extraction-cost report");
  require(report.schema_version === 1 && report.experiment === "extraction-cost-v1" && report.status === "bounded-tested" &&
    report.proof_status === "no-formal-proof" && report.protocol_sha256 === EXTRACTION_PROTOCOL_SHA256,
  "Expected the fixed bounded extraction-cost-v1 protocol without a formal-proof claim.");
  require(report.arm_budget === BUDGET, "Unexpected shared arm budget.");
  require(report.counter_model === COUNTER_MODEL, "Unexpected counter model.");
  validateLimitations(report.limitations);
  equal(report.corpus, CORPUS, "Unexpected extraction-cost corpus.");
  equal(report.arms, ARMS, "Unexpected arm declaration.");
  equal(report.comparison, COMPARISON, "Unexpected comparison declaration.");
  equal(report.encoding, ENCODING, "Unexpected encoding declaration.");
  require(Array.isArray(report.observations) && report.observations.length === PRIMARY_CASES + SECONDARY_CASES, "Expected every fixed extraction-cost case.");
  const expected = expectedCases();
  for (const row of report.observations) {
    require(row && typeof row === "object" && expected.has(row.id), "Unexpected or duplicate extraction-cost case identity.");
    const fixed = expected.get(row.id);
    expected.delete(row.id);
    validateObservation(row, fixed);
  }
  const identities = report.observations.map(row => JSON.stringify([row.variables, row.input]));
  require(new Set(identities).size === identities.length, "Corpus repeats an exact declared-variables and ordered-CNF pair.");
  const primary = report.observations.filter(row => !row.secondary);
  const secondary = report.observations.filter(row => row.secondary);
  validateSection(report.primary, primary, {
    name: "primary", fields: ["summary", "families", "random_mixed_by_binary_count"],
    mixedFamily: "random-mixed", subtotalKey: "random_mixed_by_binary_count", families: CORPUS.primary_families,
  });
  require(report.secondary.arm2_reproduces_v1 === true, "Secondary section must declare that arm 2 reproduced the fragment-interface-v1 counters.");
  validateSection(report.secondary, secondary, {
    name: "secondary", fields: ["arm2_reproduces_v1", "summary", "families", "v1_random_mixed_by_binary_count"],
    mixedFamily: "v1:random-mixed", subtotalKey: "v1_random_mixed_by_binary_count", families: SECONDARY_FAMILIES,
  });
  equal(report.outside_arms, {
    reference_work_units: sum([report.primary.summary.reference_work_units, report.secondary.summary.reference_work_units]),
    checker_work_units: sum([report.primary.summary.checker_work_units, report.secondary.summary.checker_work_units]),
  }, "Outside-arm totals are inconsistent.");
  return report;
}
