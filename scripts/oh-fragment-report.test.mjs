const roots = [];
const reportBytes = readFileSync(new URL("../artifacts/fragment-interface.json", import.meta.url));
const protocolBytes = readFileSync(new URL("../experiments/fragment-interface-protocol.md", import.meta.url));
const report = () => JSON.parse(reportBytes);
function root() {
  const path = mkdtempSync(join(tmpdir(), "peqnp-fragment-ledger-test-"));
  roots.push(path);
  for (const directory of ["artifacts", "experiments", "src"]) mkdirSync(join(path, directory));
  for (const file of ["Cargo.toml", "Cargo.lock", "rust-toolchain.toml"]) writeFileSync(join(path, file), "# synthetic source fixture\n");
  writeFileSync(join(path, "src/lib.rs"), "// Synthetic source fixture, not experimental provenance.\n");
  writeFileSync(join(path, "artifacts/fragment-interface.json"), reportBytes);
  writeFileSync(join(path, "experiments/fragment-interface-protocol.md"), protocolBytes);
  return path;
}
afterEach(() => { for (const path of roots.splice(0)) rmSync(path, { recursive: true, force: true }); });
const find = (actual, predicate) => actual.observations.find(predicate);
const withClues = actual => find(actual, row => row.fragment.clues.length > 0);
const withPaths = actual => find(actual, row => row.fragment.certificate?.kind === "opposite-paths");
const unsat = actual => find(actual, row => !row.reference.sat);
const sat = actual => find(actual, row => row.reference.sat);
const satWithClues = actual => find(actual, row => row.reference.sat && row.fragment.clues.length > 0);
const mixed = actual => find(actual, row => row.family === "random-mixed" && row.fragment.certificate?.kind === "sat");
const ternary = actual => find(actual, row => row.family === "random-ternary-only");
const chain = actual => find(actual, row => row.family === "chain-embedded");
const contradictory = actual => find(actual, row => row.family === "contradictory-fragment");

test("fragment report preserves the fixed corpus and rejects proof, protocol, and corpus changes", () => {
  const actual = report();
  expect(actual.protocol_sha256).toBe(FRAGMENT_PROTOCOL_SHA256);
  expect(validateFragmentInterface(actual)).toBe(actual);
  const proof = report();
  proof.proof_status = "proved-generally";
  expect(() => validateFragmentInterface(proof)).toThrow("without a formal-proof");
  const protocol = report();
  protocol.protocol_sha256 = "0".repeat(64);
  expect(() => validateFragmentInterface(protocol)).toThrow("without a formal-proof");
  const missing = report();
  missing.observations.pop();
  expect(() => validateFragmentInterface(missing)).toThrow("every fixed fragment-interface case");
  const duplicate = report();
  duplicate.observations[1] = duplicate.observations[0];
  expect(() => validateFragmentInterface(duplicate)).toThrow("duplicate");
  const renamed = report();
  mixed(renamed).density = 6;
  expect(() => validateFragmentInterface(renamed)).toThrow("fixed corpus");
  const seed = report();
  mixed(seed).effective_seed = "1";
  expect(() => validateFragmentInterface(seed)).toThrow("fixed corpus");
  const control = report();
  chain(control).input[0][0] *= -1;
  expect(() => validateFragmentInterface(control)).toThrow("Engineered control input");
  const cycle = report();
  contradictory(cycle).input[1] = [1, 2];
  expect(() => validateFragmentInterface(cycle)).toThrow("Engineered control input");
  const shape = report();
  mixed(shape).input[mixed(shape).input.length - 1] = [1, 1];
  expect(() => validateFragmentInterface(shape)).toThrow("Random clause shape");
  const width = report();
  ternary(width).input[0] = [1, 2];
  expect(() => validateFragmentInterface(width)).toThrow("Random clause shape");
  const counts = report();
  mixed(counts).fragment_clauses++;
  expect(() => validateFragmentInterface(counts)).toThrow("Clause or used-variable counts");
  const corpus = report();
  corpus.corpus.families["random-mixed"] = 109;
  expect(() => validateFragmentInterface(corpus)).toThrow("Unexpected fragment-interface corpus");
  const declaration = report();
  declaration.comparison.restricted_to = "every case";
  expect(() => validateFragmentInterface(declaration)).toThrow("comparison declaration");
  const extra = report();
  extra.speedup_claim = true;
  expect(() => validateFragmentInterface(extra)).toThrow("Unexpected fragment-interface report fields");
});

