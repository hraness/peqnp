test("certificates, clue paths, derived units, controls and checker counters are re-checked against the raw clauses", () => {
  const values = report();
  sat(values).fragment.certificate.values = sat(values).fragment.certificate.values.slice(1);
  expect(() => validateFragmentInterface(values)).toThrow("one Boolean per declared variable");
  const falsified = report();
  const target = mixed(falsified);
  target.input[target.input.length - 1] = [target.fragment.certificate.values[0] ? -1 : 1, target.fragment.certificate.values[1] ? -2 : 2];
  expect(() => validateFragmentInterface(falsified)).toThrow("does not satisfy every width-at-most-two clause");
  const path = report();
  withClues(path).fragment.clues[0].path.clauses.pop();
  expect(() => validateFragmentInterface(path)).toThrow("one clause per edge");
  const edge = report();
  const clue = withClues(edge).fragment.clues[0];
  clue.path.clauses[0] = (clue.path.clauses[0] + 1) % withClues(edge).input.length;
  expect(() => validateFragmentInterface(edge)).toThrow();
  const wide = report();
  const cited = withClues(wide);
  cited.fragment.clues[0].path.clauses[0] = cited.input.findIndex(raw => raw.length === 3);
  expect(() => validateFragmentInterface(wide)).toThrow("does not support");
  const endpoints = report();
  withClues(endpoints).fragment.clues[0].literal *= -1;
  expect(() => validateFragmentInterface(endpoints)).toThrow();
  const opposite = report();
  withPaths(opposite).fragment.certificate.positive_to_negative.nodes.reverse();
  expect(() => validateFragmentInterface(opposite)).toThrow("endpoints");
  const order = report();
  const ordered = find(order, row => row.fragment.clues.length > 1);
  ordered.fragment.derived_units.reverse();
  expect(() => validateFragmentInterface(order)).toThrow("clue literals in order");
  const backbone = report();
  const forced = satWithClues(backbone);
  forced.reference.backbone = forced.reference.backbone.filter(unit => unit !== forced.fragment.derived_units[0]);
  expect(() => validateFragmentInterface(backbone)).toThrow("subset of the reference backbone");
  const emptyFragment = report();
  ternary(emptyFragment).fragment.derived_units = [1];
  expect(() => validateFragmentInterface(emptyFragment)).toThrow();
  const residual = report();
  ternary(residual).fragment.phases.residual.formula_checks++;
  ternary(residual).fragment.phases.residual.clause_reads--;
  expect(() => validateFragmentInterface(residual)).toThrow("Residual counters on an empty fragment");
  const refuted = report();
  const cycle = contradictory(refuted);
  for (const key of ["work_units", "clause_reads"]) cycle.fragment.phases.residual[key] = 5;
  cycle.fragment.residual_work_units = 5;
  cycle.fragment.total_work_units += 5;
  expect(() => validateFragmentInterface(refuted)).toThrow("without extraction, appends, or residual work");
  const chained = report();
  chain(chained).fragment.clues = [];
  chain(chained).fragment.derived_units = [];
  expect(() => validateFragmentInterface(chained)).toThrow("derive exactly the selected sign");
  const unsatBackbone = report();
  unsat(unsatBackbone).reference.backbone = [];
  expect(() => validateFragmentInterface(unsatBackbone)).toThrow("UNSAT reference");
  const nullBackbone = report();
  sat(nullBackbone).reference.backbone = null;
  expect(() => validateFragmentInterface(nullBackbone)).toThrow("distinct forced literals");
  const checker = report();
  withClues(checker).checks.clues_valid--;
  expect(() => validateFragmentInterface(checker)).toThrow("Checker outcome");
  const certificate = report();
  withPaths(certificate).checks.certificate_valid = false;
  expect(() => validateFragmentInterface(certificate)).toThrow("Checker outcome");
});

test("local ingestion is additive, repeatable, and records phases, ratios and the comparison without a speedup proposition", () => {
  const path = root();
  initializeLedger(path);
  const first = recordFragmentInterface(path, "artifacts/fragment-interface.json");
  expect(first.inserted).toBe(5);
  expect(first.verification.records).toBe(11);
  const second = recordFragmentInterface(path, "artifacts/fragment-interface.json");
  expect(second.inserted).toBe(0);
  expect(second.verification).toEqual(first.verification);
  const oh = openLedger(path);
  try {
    const observation = oh.list({ kind: "assertion", limit: 20 }).find(record => record.key.startsWith("assertion:fragment-interface-"));
    expect(observation.value.stance).toBe("bounded-observation");
    expect(observation.value.formalProofAccepted).toBe(false);
    expect(observation.value.statement).toBe("statement:fragment-interface-v1-comparison");
    expect(oh.get("statement:fragment-interface-v1-comparison").value.domain).toContain("no total-work improvement");
    expect(oh.get("edition:fragment-interface-" + first.reportSha256).value.path).toBe("artifacts/fragment-interface.json");
    const evidence = oh.list({ kind: "evidence", limit: 20 }).find(record => record.key.startsWith("evidence:fragment-interface-"));
    expect(evidence.value.kind).toBe("finite-fragment-interface-report");
    expect(evidence.value.measuredSummary).toEqual(report().summary);
    expect(evidence.value.comparison).toEqual(report().comparison);
    expect(evidence.value.phaseWorkUnits).toEqual(report().summary.arms.fragment.phases);
    expect(evidence.value.outsideArmWorkUnits).toEqual(report().outside_arms);
    expect(evidence.value.enumerationRatios).toEqual(report().summary.enumeration_ratio);
    expect(evidence.value.limitations).toEqual(report().limitations);
    expect(evidence.value.frozenLibrarySha256).toBeUndefined();
    expect(evidence.value.formalProofAccepted).toBe(false);
    expect(oh.get("assertion:p-equals-np-hypothesis").value.stance).toBe("research-hypothesis");
  } finally { oh.store.close(); }
});

test("invalid report and changed protocol fail before initializing or changing research state", () => {
  const path = root();
  const wrong = report();
  wrong.summary.arms.fragment.derived_units++;
  writeFileSync(join(path, "artifacts/fragment-interface.json"), JSON.stringify(wrong));
  expect(() => recordFragmentInterface(path, "artifacts/fragment-interface.json")).toThrow("Summary differs");
  expect(existsSync(join(path, ".oh"))).toBe(false);
  writeFileSync(join(path, "artifacts/fragment-interface.json"), reportBytes);
  const initial = initializeLedger(path);
  writeFileSync(join(path, "experiments/fragment-interface-protocol.md"), "changed protocol\n");
  expect(() => recordFragmentInterface(path, "artifacts/fragment-interface.json")).toThrow("fixed protocol identity");
  const oh = openLedger(path);
  expect(oh.verify()).toEqual(initial.verification);
  oh.store.close();
});
