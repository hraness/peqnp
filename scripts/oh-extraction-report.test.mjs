  sat(values).settled.certificate.values = sat(values).settled.certificate.values.slice(1);
  expect(() => validateExtractionCost(values)).toThrow("one Boolean per declared variable");
  const falsified = report();
  const target = mixed(falsified);
  target.input[target.input.length - 1] = [target.per_literal.certificate.values[0] ? -1 : 1, target.per_literal.certificate.values[1] ? -2 : 2];
  expect(() => validateExtractionCost(falsified)).toThrow("does not satisfy every width-at-most-two clause");
  const path = report();
  withClues(path).settled.clues[0].path.clauses.pop();
  expect(() => validateExtractionCost(path)).toThrow("one clause per edge");
  const edge = report();
  const clue = withClues(edge).per_literal.clues[0];
