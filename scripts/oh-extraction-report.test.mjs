  cited.settled.clues[0].path.clauses[0] = cited.input.findIndex(raw => raw.length === 3);
  expect(() => validateExtractionCost(wide)).toThrow("does not support");
  const endpoints = report();
  withClues(endpoints).settled.clues[0].literal *= -1;
  expect(() => validateExtractionCost(endpoints)).toThrow();
