test("local ingestion is additive, repeatable, and records both sections, the comparisons and settled stats without a speedup proposition", () => {
  const path = root();
  initializeLedger(path);
  const first = recordExtractionCost(path, "artifacts/extraction-cost.json");
  const second = recordExtractionCost(path, "artifacts/extraction-cost.json");
  expect(second.inserted).toBe(0);
  expect(second.verification).toEqual(first.verification);
  const oh = openLedger(path);
  try {
    // The 1.78 MB canonical report exceeds the pinned runtime's 1 MiB record
    // bound, so the edition stores it as ordered observation parts that
    // reassemble to the exact report; the five-record pattern gains one
    // edition per part.
    const edition = oh.get("edition:extraction-cost-" + first.reportSha256);
    expect(edition.value.report.observations).toBeUndefined();
    expect(edition.value.observationCount).toBe(338);
    const parts = edition.value.observationParts;
    expect(parts.length).toBeGreaterThan(1);
    expect(edition.dependencies).toEqual(parts);
    expect(first.inserted).toBe(5 + parts.length);
    expect(first.verification.records).toBe(11 + parts.length);
    const assembled = editionReport(edition, key => oh.get(key));
    expect(canonicalJson(assembled)).toBe(canonicalJson(report()));
    for (const [index, key] of parts.entries()) {
      const part = oh.get(key).value;
      expect([part.part, part.parts, part.reportSha256, part.path]).toEqual([index, parts.length, first.reportSha256, "artifacts/extraction-cost.json"]);
      expect(Buffer.byteLength(canonicalJson(part), "utf8")).toBeLessThan(1024 * 1024);
    }
    expect(() => editionReport(edition, key => key === parts[1] ? oh.get(parts[0]) : oh.get(key))).toThrow("inconsistent with its edition");
    expect(() => editionReport(edition, key => key === parts[0] ? null : oh.get(key))).toThrow("missing");
    const observation = oh.list({ kind: "assertion", limit: 20 }).find(record => record.key.startsWith("assertion:extraction-cost-"));
    expect(observation.value.stance).toBe("bounded-observation");
    expect(observation.value.formalProofAccepted).toBe(false);
    expect(observation.value.statement).toBe("statement:extraction-cost-v1-comparison");
    const statement = oh.get("statement:extraction-cost-v1-comparison").value;
    expect(statement.proposition).toContain("three arms");
    expect(statement.domain).toContain("no total-work improvement");
    expect(oh.get("edition:extraction-cost-" + first.reportSha256).value.path).toBe("artifacts/extraction-cost.json");
    const evidence = oh.list({ kind: "evidence", limit: 20 }).find(record => record.key.startsWith("evidence:extraction-cost-"));
    const actual = report();
    expect(evidence.value.kind).toBe("finite-extraction-cost-report");
    expect(evidence.value.measuredSummary).toEqual({ primary: actual.primary.summary, secondary: actual.secondary.summary });
    expect(evidence.value.comparison).toEqual(actual.comparison);
    expect(Object.keys(evidence.value.comparisons.primary).sort()).toEqual(["extraction_settled_vs_per_literal", "per_literal_vs_baseline", "settled_vs_baseline", "settled_vs_per_literal"]);
    expect(evidence.value.comparisons.secondary).toEqual(actual.secondary.summary.comparisons);
    expect(evidence.value.extractionWorkUnits.primary).toEqual({
      per_literal: actual.primary.summary.arms.per_literal.phases.extraction_work_units,
      settled: actual.primary.summary.arms.settled.phases.extraction_work_units,
    });
    expect(evidence.value.settledStats.secondary).toEqual(actual.secondary.summary.settled_stats);
    expect(evidence.value.outsideArmWorkUnits).toEqual(actual.outside_arms);
    expect(evidence.value.enumerationRatios.primary).toEqual(actual.primary.summary.enumeration_ratio);
    expect(evidence.value.limitations).toEqual(actual.limitations);
    expect(evidence.value.frozenLibrarySha256).toBeUndefined();
    expect(evidence.value.formalProofAccepted).toBe(false);
    expect(oh.get("assertion:p-equals-np-hypothesis").value.stance).toBe("research-hypothesis");
  } finally { oh.store.close(); }
}, 120_000);

test("invalid report and changed protocol fail before initializing or changing research state", () => {
  const path = root();
  const wrong = report();
  wrong.primary.summary.arms.settled.derived_units++;
  writeFileSync(join(path, "artifacts/extraction-cost.json"), JSON.stringify(wrong));
  expect(() => recordExtractionCost(path, "artifacts/extraction-cost.json")).toThrow("primary summary differs");
  expect(existsSync(join(path, ".oh"))).toBe(false);
  writeFileSync(join(path, "artifacts/extraction-cost.json"), reportBytes);
  const initial = initializeLedger(path);
  writeFileSync(join(path, "experiments/extraction-cost-protocol.md"), "changed protocol\n");
  expect(() => recordExtractionCost(path, "artifacts/extraction-cost.json")).toThrow("fixed protocol identity");
  const oh = openLedger(path);
  expect(oh.verify()).toEqual(initial.verification);
  oh.store.close();
}, 120_000);
